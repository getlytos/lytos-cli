/**
 * `lyt board` and `lyt show` with the intent layer (ISS-0164).
 *
 * An epic is shown with its leaves indented and a progress count, derived on read.
 * A project that adopts none of the fields must see exactly the board it saw
 * before: the first block compares it with output captured from the build that
 * preceded this change.
 */

import { describe, it, expect, afterEach } from "vitest";
import { resolve, join } from "path";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { spawnSync } from "child_process";
import { type Fixture } from "../helpers/fixtures.js";
import {
  createIntentFixture,
  moveCard,
  writeCard,
} from "../helpers/cards.js";

const CLI = resolve(__dirname, "../../dist/cli.js");

function run(args: string, cwd: string) {
  const result = spawnSync("node", [CLI, ...args.split(" ")], {
    cwd,
    encoding: "utf-8",
    env: { ...process.env, NO_COLOR: "1" },
  });
  return {
    stdout: result.stdout || "",
    stderr: result.stderr || "",
    exitCode: result.status ?? 0,
  };
}

let fixture: Fixture;

afterEach(() => {
  if (fixture) fixture.cleanup();
});

const boardMd = (cwd: string) =>
  readFileSync(join(cwd, ".lytos/issue-board/BOARD.md"), "utf-8").replace(
    /\*\*Last generated\*\*: .*/,
    "**Last generated**: DATE"
  );

/** Four plain cards, no intent field. The goldens below were captured before ISS-0164. */
function plainProject(): string {
  fixture = createIntentFixture();
  const board = join(fixture.cwd, ".lytos", "issue-board");
  const w = (dir: string, file: string, body: string) => {
    mkdirSync(join(board, dir), { recursive: true });
    writeFileSync(join(board, dir, file), body);
  };
  w("1-backlog", "ISS-0001-setup-db.md", `---\nid: ISS-0001\ntitle: "Setup database"\ntype: feat\npriority: P1-high\neffort: M\nstatus: 1-backlog\ndepends: []\ncreated: 2026-04-10\n---\n\n# ISS-0001\n`);
  w("3-in-progress", "ISS-0002-create-api.md", `---\nid: ISS-0002\ntitle: "Create REST API"\ntype: feat\npriority: P1-high\neffort: L\ncomplexity: heavy\nstatus: 3-in-progress\ndepends: [ISS-0001]\nassignee: tester\ncreated: 2026-04-10\n---\n\n# ISS-0002\n`);
  w("5-done", "ISS-0003-init-project.md", `---\nid: ISS-0003\ntitle: "Initialize project"\ntype: chore\npriority: P0-critical\neffort: XS\nstatus: 5-done\ndepends: []\ncreated: 2026-04-08\nupdated: 2026-04-09\n---\n\n# ISS-0003\n`);
  w("2-sprint", "ISS-0004-fix-it.md", `---\nid: ISS-0004\ntitle: "Fix the thing"\ntype: fix\npriority: P2-normal\neffort: S\nstatus: 2-sprint\ndepends: []\ncreated: 2026-04-10\n---\n\n# ISS-0004\n`);
  return fixture.cwd;
}

