describe("a project that adopts none of the intent fields", () => {
  it("sees the terminal board exactly as before", () => {
    const r = run("board", plainProject());
    expect(r.exitCode).toBe(0);
    expect(r.stdout).toBe(GOLDEN_TERMINAL);
    expect(r.stdout).not.toContain("EPICS");
  });

  it("gets exactly the same BOARD.md as before", () => {
    const cwd = plainProject();
    run("board", cwd);
    expect(boardMd(cwd)).toBe(GOLDEN_BOARD_MD);
  });

  it("gets no Epics section from `lyt move`, which regenerates BOARD.md too", () => {
    const cwd = plainProject();
    run("move ISS-0004 4-review", cwd);
    expect(boardMd(cwd)).not.toContain("Epics");
  });

  it("gets no `epics` key in the JSON board", () => {
    const data = JSON.parse(run("board --json", plainProject()).stdout);
    expect(Object.keys(data)).toEqual(["generated", "nextNumber", "warnings", "columns"]);
  });

  it("gets no intent block in `lyt show`, text or JSON", () => {
    const cwd = plainProject();
    const text = run("show ISS-0002", cwd).stderr;
    expect(text).not.toMatch(/Epic|Milestone|Leaves/);
    const detail = JSON.parse(run("show ISS-0002 --json", cwd).stdout);
    expect(Object.keys(detail).sort()).toEqual([
      "body", "branch", "checklist", "checklistDone", "checklistTotal", "complexity",
      "created", "daysOpen", "dependencies", "dod", "effort", "id", "parkReason",
      "parkedAt", "priority", "progress", "skill", "skillsAux", "status", "title", "updated",
    ]);
  });
});

function epicProject(): string {
  fixture = createIntentFixture();
  const cwd = fixture.cwd;
  writeCard(cwd, "ISS-0010", {
    type: "epic",
    title: "Big outcome",
    fields: { phase: "discovery", milestone: "v1.7" },
  });
  writeCard(cwd, "ISS-0011", { title: "Leaf one", dir: "5-done", fields: { parent: "ISS-0010" } });
  writeCard(cwd, "ISS-0012", { title: "Leaf two", dir: "2-sprint", fields: { parent: "ISS-0010" } });
  writeCard(cwd, "ISS-0013", { title: "Leaf three", fields: { parent: "ISS-0010" } });
  writeCard(cwd, "ISS-0020", { type: "fix", title: "Unrelated fix" });
  return cwd;
}

describe("lyt board — an epic with its leaves and a progress count", () => {
  it("shows the epic, its leaves indented, and the progress, in the terminal", () => {
    const r = run("board", epicProject());
    expect(r.exitCode).toBe(0);
    expect(r.stdout).toContain("EPICS (1)");
    expect(r.stdout).toMatch(/ISS-0010\s+Big outcome\s+discovery\s+v1\.7\s+\S+\s+1\/3\s+33%/);
    expect(r.stdout).toMatch(/├── ✓ ISS-0011\s+Leaf one\s+5-done/);
    expect(r.stdout).toMatch(/├── ○ ISS-0012\s+Leaf two\s+2-sprint/);
    expect(r.stdout).toMatch(/└── ○ ISS-0013\s+Leaf three\s+1-backlog/);
  });

  it("keeps every card in its own column", () => {
    const out = run("board", epicProject()).stdout;
    expect(out).toContain("BACKLOG (3)"); // the epic, a leaf, the fix
    expect(out).toContain("SPRINT (1)");
    expect(out).toContain("DONE (1)");
  });

  it("writes an Epics section into BOARD.md, derived, with links", () => {
    const cwd = epicProject();
    run("board", cwd);
    const md = boardMd(cwd);
    expect(md).toContain("## Epics");
    expect(md).toContain("- [ISS-0010](1-backlog/ISS-0010-card.md) Big outcome — 1/3 leaves done (33%)");
    expect(md).toContain("  - [ISS-0011](5-done/ISS-0011-card.md) Leaf one — 5-done");
    expect(md).toContain("  - [ISS-0012](2-sprint/ISS-0012-card.md) Leaf two — 2-sprint");
    expect(md.indexOf("## Epics")).toBeGreaterThan(md.indexOf("### Archive"));
  });

  it("changes when a leaf moves, through the CLI", () => {
    const cwd = epicProject();
    expect(run("board --json", cwd).stdout).toContain('"done": 1');
    expect(run("move ISS-0013 4-review", cwd).exitCode).toBe(0);
    expect(run("close ISS-0013", cwd).exitCode).toBe(0);
    const epic = JSON.parse(run("board --json", cwd).stdout).epics[0];
    expect(epic.progress).toEqual({ done: 2, total: 3, percent: 67 });
    expect(boardMd(cwd)).toContain("2/3 leaves done (67%)");
    expect(run("board", cwd).stdout).toMatch(/2\/3\s+67%/);
  });

  it("regenerates the same Epics section from `lyt move` as from `lyt board`", () => {
    const cwd = epicProject();
    run("move ISS-0012 4-review", cwd);
    const fromMove = boardMd(cwd);
    run("board", cwd);
    expect(boardMd(cwd)).toBe(fromMove);
    expect(fromMove).toContain("## Epics");
  });

  it("adds an epics array to the JSON board, only when there is an epic", () => {
    const data = JSON.parse(run("board --json", epicProject()).stdout);
    expect(data.epics).toHaveLength(1);
    expect(data.epics[0]).toMatchObject({
      id: "ISS-0010",
      title: "Big outcome",
      phase: "discovery",
      milestone: "v1.7",
      progress: { done: 1, total: 3, percent: 33 },
    });
    expect(data.epics[0].leaves.map((l: { id: string; status: string }) => [l.id, l.status])).toEqual([
      ["ISS-0011", "5-done"],
      ["ISS-0012", "2-sprint"],
      ["ISS-0013", "1-backlog"],
    ]);
  });

  it("shows an epic with no leaf yet as 0 of 0, not as an error", () => {
    fixture = createIntentFixture();
    writeCard(fixture.cwd, "ISS-0010", { type: "epic", title: "Empty epic" });
    const out = run("board", fixture.cwd).stdout;
    expect(out).toContain("EPICS (1)");
    expect(out).toContain("no leaf yet");
  });

  it("keeps a closed leaf counted once its card is archived", () => {
    const cwd = epicProject();
    moveCard(cwd, "ISS-0011", "5-done", "archive/2026-Q4");
    const epic = JSON.parse(run("board --json", cwd).stdout).epics[0];
    expect(epic.progress).toEqual({ done: 1, total: 3, percent: 33 });
  });
});

describe("lyt show — an epic lists its leaves, a leaf names its epic", () => {
  it("lists the leaves and the progress of an epic", () => {
    const r = run("show ISS-0010", epicProject());
    expect(r.exitCode).toBe(0);
    expect(r.stderr).toMatch(/Phase:\s+discovery/);
    expect(r.stderr).toMatch(/Milestone:\s+v1\.7/);
    expect(r.stderr).toMatch(/Leaves:\s+\S+\s+1\/3\s+33%/);
    expect(r.stderr).toMatch(/✓ ISS-0011\s+Leaf one\s+5-done/);
    expect(r.stderr).toMatch(/○ ISS-0012\s+Leaf two\s+2-sprint/);
  });

  it("names the epic of a leaf", () => {
    const r = run("show ISS-0012", epicProject());
    expect(r.stderr).toMatch(/Epic:\s+ISS-0010 — Big outcome \(discovery\)/);
    expect(r.stderr).not.toMatch(/Milestone:/); // only what the card names itself
  });

  it("gives the same facts as JSON, under `intent`", () => {
    const d = JSON.parse(run("show ISS-0010 --json", epicProject()).stdout);
    expect(d.intent.phase).toBe("discovery");
    expect(d.intent.progress).toEqual({ done: 1, total: 3, percent: 33 });
    expect(d.intent.leaves.map((l: { id: string }) => l.id)).toEqual([
      "ISS-0011",
      "ISS-0012",
      "ISS-0013",
    ]);
    const leaf = JSON.parse(run("show ISS-0012 --json", epicProject()).stdout);
    expect(leaf.intent.parent).toMatchObject({ id: "ISS-0010", found: true });
  });

  it("says when the parent of a leaf is not on the board", () => {
    fixture = createIntentFixture();
    writeCard(fixture.cwd, "ISS-0011", { fields: { parent: "ISS-0999" } });
    const r = run("show ISS-0011", fixture.cwd);
    expect(r.stderr).toMatch(/Epic:\s+ISS-0999 \(not found\)/);
  });
});
